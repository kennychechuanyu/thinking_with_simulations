# Step 5: what an experiment could establish (Section 6)
# The reader chooses a saved case and designs the experiment (the number of
# participants and the pear trials analyzed), then detects a difference,
# compares the three candidates by predicting held-out participants, and sees
# how often the planned analysis reaches each decision. The responses and every
# analysis come from data/inference_cases.rds, written by
# shiny_app/make_inference_cases.R from the paper's simulation study. Nothing
# is fitted here. Which process generated the case is revealed in Step 6.

