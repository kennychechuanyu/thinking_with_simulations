                "If all the candidates share a mistaken assumption, for example about the
                 starting values or the response function, choosing the best of them cannot test
                 it. Step 6 examines such an assumption."),
        aside("Section 6, Tables 7 to 9, Figures 7 and 8 and Box 5."))))
