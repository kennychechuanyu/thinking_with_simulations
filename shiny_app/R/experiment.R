           apple. But carried-over value also gives them a difference before much learning has
           occurred, so over all ten pear trials, much of their discrepancy from the adaptive
           model's predictions lies in the first pear trials. On pear trials 8–10 alone, they come
           very close to those predictions."),
        aside("Section 6.4.")),
      h3("How reliable the planned analysis would be"),
      p("The result of one simulated experiment depends on the particular responses drawn. The
         tutorial therefore simulated 400 experiments for each generating process and sample
         size, analyzed each with the same candidates and decision rule, and repeated the
         analysis on pear trials 1–6 and on pear trials 8–10 of the same responses. The processes
         were:"),
      tags$ul(
        tags$li("Carried associability, the process the carryover candidate represents: the
                 compound trials change associability, and part of that change carries over to
                 the pear trials."),
        tags$li("Carried learned value, which the fixed-rate candidate can represent: learning
                 rates stay fixed, and a B–D difference arises because learned values for the
                 apple carry over. Favoring associability carryover would be a mistake here."),
        tags$li("Reset associability, the process the reset candidate represents:
                 associability can change during the pear trials, but nothing that changed
