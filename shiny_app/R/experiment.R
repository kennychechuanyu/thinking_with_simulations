experiment_server <- function(input, output, answers, add_note, flag) {

  # The design
  output$e_case <- renderUI({
    a <- answers$e_design
    if (is.null(a)) radioButtons("e_design_set", span(class = "visually-hidden", "Case to examine"),
      inline = TRUE, choiceNames = unname(set_labels), choiceValues = names(set_labels),
      selected = "value")
    else p(span(class = "answered-label", "Case examined"), set_labels[[a$set]])
  })
  rec_choices <- c(
    late = "The responses on pear trials 8–10, as a final test might record.",
    early = "The responses on pear trials 1–6, when the difference emerges.",
    full = "The responses on all ten pear trials.")
  design_items <- list(
    item("n", "How many participants?", c(`40` = "40", `160` = "160")),
    item("rec", "Which responses are analyzed?", rec_choices))
  ask_server("e_design", input, output, answers, design_items,
    reason = "Why these responses? Say what you hope they will tell you.",
    reason_required = TRUE, button = "Run the experiment",
    on_submit = function(a) {
      a$set <- input$e_design_set
      if (is.null(a$set) || !(a$set %in% names(set_labels))) a$set <- "value"
      answers$e_design <- a
      add_note("Step 5", "Design",
        "How many participants, and which responses are analyzed?",
        paste0(set_labels[[a$set]], ", ", a$n, " participants, ", view_labels[[a$rec]],
               " analyzed. Reason: ", a$reason),
        settings = design_set(a))
    })
  design_set <- function(a = answers$e_design) {
    cs <- cases[[a$set]][[a$n]]
    paste0(set_labels[[a$set]], ", ", a$n, " participants, ", view_labels[[a$rec]],
      " analyzed; dataset ID = ", cs$id, "; seed = ", cs$seed, "; parameter set = ", cs$config,
      "; earlier trials: 10 A+ and 10 X+ with the apple; compound trials: 10 AB+ and 10 CD+",
      " with the apple; pear trials: 10 with B alone and 10 with D alone, block order",
      " counterbalanced; physical lights counterbalanced equally",
      "; p(yes) = logistic(b + gamma * V), each response drawn as yes with that probability",
      "; b and gamma estimated in every candidate; candidates: fixed-rate (Rescorla–Wagner),",
      " reset and carryover (adaptive model), each estimating g_V",
      "; two-fold cross-validation with the held-out log score; carryover favored if both score",
      " differences exceed 2 SE, another candidate favored if either is below -2 SE, otherwise unresolved",
      "; mean difference: equal-weight average of the two counterbalancing groups, 95% t interval",
      " with Welch–Satterthwaite degrees of freedom; per-trial intervals: Agresti–Min for paired proportions")
  }

  case <- reactive({ a <- answers$e_design; req(a); cases[[a$set]][[a$n]] })
  design <- reactive({ a <- answers$e_design; req(a); case()$designs[[a$rec]] })

  output$e_design_line <- renderUI({
    a <- answers$e_design; req(a)
    P("<b>", set_labels[[a$set]], "</b>, ", a$n, " participants, ", view_labels[[a$rec]],
      " analyzed.")
  })
  output$e_records <- renderPlot(plot_records(case(), cols = design()$cols))
  output$e_participants <- renderPlot(plot_participants(case(), design()))
  effect_text <- function() {
    e <- design()$effect
    d <- participant_differences(case(), design()$cols)
    paste0("For your ", case()$n, " participants and the pear trials you kept, the mean
      difference in the proportion of yes responses, D minus B, is ", num(e[["estimate"]]),
      " (95% interval ", num(e[["lower"]]), " to ", num(e[["upper"]]), "). Of the ", nrow(d),
      " participants, ", sum(d$difference <= 0), " gave D no more yes responses than B. In the
      group where light 1 served as B, the mean difference is ",
      num(mean(d$difference[d$group == 1])), ", and where light 2 served as B it is ",
      num(mean(d$difference[d$group == -1])), ".",
      if (e[["detected"]] == 1) " The interval lies above zero, so a positive B–D difference is
        detected in this sample."
      else if (e[["upper"]] < 0) " The interval lies below zero, so it gives no support for a
        positive B–D difference."
      else " The interval includes zero, so a positive B–D difference is not detected in this
        sample.")
  }
  output$e_effect <- renderUI(p(effect_text()))

  # What the responses show
  e1_choices <- c(
    more = "The mean D-minus-B difference is positive, with a 95% interval above zero.",
    none = "The 95% interval does not lie above zero, so a positive difference is not detected.",
    assoc = "B carried a lower associability into the pear trials.",
    value = "Learned values for the apple carried over to the pear.")
  e1_items <- list(item("e", "What do these responses show?", e1_choices))
  ask_server("e1", input, output, answers, e1_items,
    feedback = function(a) {
      e <- design()$effect
      tagList(
        p(if (a$e %in% c("assoc", "value"))
          "The responses show only whether yes responses differ between B and D. Associability
           and learned value are explanations to compare, and more than one process can produce
           the same difference."
        else if (a$e == "more" && e[["detected"]] != 1)
          "A positive difference needs the whole interval to lie above zero, and this interval
           does not."
        else if (a$e == "none" && e[["detected"]] == 1)
          "The whole interval lies above zero, so a positive difference is detected. That
           supports a response difference but does not identify its source."
        else "Your reading matches the interval. What could have produced this pattern?"))
    },
    on_submit = function(a) add_note("Step 5", "Detecting a difference",
      "What do these responses show?", e1_choices[[a$e]], result = effect_text(),
      settings = design_set()))

  # Box 5: what produced the difference?
  est_choices <- c(yes = "Yes. Only a lower associability for B makes D get more yes responses.",
                   no = "No. Learned values for the apple carried over to the pear could also produce it.")
  look_choices <- c(first = "The responses on the first pear trial with each light.",
                    last = "The responses on the last pear trials.",
                    overall = "The overall proportion of yes responses.")
  e2_items <- list(
    item("est", "Suppose the participants answered yes more often to D than to B. Does this
      establish that B carried a lower associability into the pear trials?", est_choices),
    item("look", "What in the sequence of responses could show whether the difference was
      present from the start or developed during the pear trials?", look_choices))
  e2_text <- "A B–D difference could arise because learned values for the apple carry over or
    because the lights carry over different associabilities (Step 3). With a shared response
    function, only carried-over learned value can make the first-response probabilities differ
    (Step 4). The mean difference averages over the
    pear trials, whereas the responses on each pear trial show when the difference appears."
  ask_server("e2", input, output, answers, e2_items, button = "See the responses on each pear trial",
    feedback = function(a) tagList(
      if (a$est == "yes") p("A difference in responses does not show where it came from. Step 3
        showed that carried-over learned value can also put D ahead of B."),
      if (a$look != "first") p(if (a$look == "last") "By the last pear trials both kinds of gap
        can look alike. The first pear trial is where they differ most clearly." else "The
        overall proportion mixes all the pear trials, so it cannot show when the difference
        appeared."),
      p(e2_text)),
    on_submit = function(a) add_note("Step 5", "What produced the difference?",
      e2_items[[1]]$label, paste0(est_choices[[a$est]], " To look at: ", look_choices[[a$look]]),
      result = e2_text, settings = design_set()))
  output$e_contrast <- renderPlot({ req(answers$e2); plot_contrast(case(), design()) })
  output$e_contrast_text <- renderUI({
    req(answers$e2)
    d <- design()
    if (!(1 %in% d$cols)) return(P("Your analysis kept pear trials ", min(d$cols), "&ndash;",
      max(d$cols), ", so it cannot show whether the difference was present on the first pear
      trial."))
    first <- d$by_trial[d$by_trial$trial == 1, ]
    P("On the first pear trial, the observed difference is ", num(first$estimate), "
      (approximate 95% interval ", num(first$lower), " to ", num(first$upper), "). ",
      if (first$lower > 0) "This interval lies above zero, so the first responses already
        differ. Step 6 tests them with an exact paired test."
      else "This interval includes zero. Step 6 tests the first responses with an exact paired
        test.")
  })

  # The comparison of the candidates
  e3_choices <- c(
    process = "That B carried a lower associability into the pear trials in these participants.",
    best = "That, among these three candidates, the carryover candidate predicts new participants best.")
  e3_items <- list(item("pref", "Before you see the comparison: if the carryover candidate
    predicted held-out participants better than both alternatives by more than the decision
    margins, what would that show?", e3_choices))
  e3_text <- "A preference applies only to the candidates that were compared. The scores measure how
    well these candidates predict participants whose responses were held out. Whether one of
    them captures the process that produced the responses is a separate question, which Step 6
    takes up."
  ask_server("e3", input, output, answers, e3_items, button = "Run the comparison",
    feedback = function(a) tagList(
      if (a$pref == "process") p("A candidate can win this comparison while sharing a mistaken
        assumption with every alternative, and the process that generated the responses may be
        missing from the candidates."),
      p(e3_text)),
    on_submit = function(a) add_note("Step 5", "What a preference would show", e3_items[[1]]$label,
      e3_choices[[a$pref]], result = paste0(e3_text, " ", score_sentence("estimated")),
      settings = paste0(design_set(), "; ", policy_label[["estimated"]])))

  # Score differences and their standard errors to one decimal; where both are
  # below .05, to two significant digits, so that the decision can be checked
  # from the printed numbers.
  score_num <- function(x, difference, se) {
    if (abs(difference) >= .05 || se >= .05) num0(x, 1)
    else if (x == 0) "0" else formatC(x, digits = 2, format = "fg", flag = "#")
  }
  score_sentence <- function(policy) {
    d <- design(); scores <- d$scores[[policy]]
    f <- scores[scores$against == "fixed", ]; r <- scores[scores$against == "reset", ]
    bar <- function(s) paste0(score_num(s$difference, s$difference, s$se), ", SE ",
      score_num(s$se, s$difference, s$se), ", so the bar runs from ",
      score_num(s$difference - 2 * s$se, s$difference, s$se), " to ",
      score_num(s$difference + 2 * s$se, s$difference, s$se))
    paste0("Carryover minus fixed-rate: ", bar(f), ". Carryover minus reset: ", bar(r),
           ". Under the decision rule, the comparison ", decision_text[[d$decision[[policy]]]], ".",
           if (near_reset_scores(scores)) " The carryover and reset candidates have nearly
             identical held-out scores. A difference this small can still meet the rule, and it
             does not show how precisely carryover was estimated.")
  }
  output$e_scores <- renderPlot({ req(answers$e3); plot_scores(design()$scores$estimated) })
  output$e_scores_text <- renderUI({ req(answers$e3); p(score_sentence("estimated")) })

  # The repeated experiments
  rates_for <- function(source, n, view) rates[rates$scenario == source & rates$n == n &
                                                 rates$view == view, ]
  output$e_rates <- renderUI({
    req(answers$e3)
    a <- answers$e_design
    # One row of percentages; with design = TRUE it also names the design, and
    # the reader's own design is marked.
    row <- function(src, n, view, design = FALSE) {
      r <- rates_for(src, n, view)
      mine <- design && n == as.integer(a$n) && view == a$rec
      tags$tr(class = if (mine) "mine",
        tags$td(class = "nowrap", process_names[[src]]),
        if (design) tagList(tags$td(class = "nowrap", paste0(view_labels[[view]],
                                                            if (mine) " (yours)")), tags$td(n)),
        tags$td(pct(r$detected)), tags$td(pct(r$carry)), tags$td(pct(r$unresolved)),
        tags$td(pct(r$no_carry)))
    }
    heads <- function(full) tags$thead(tags$tr(tags$th("Responses generated by"),
      if (full) tagList(tags$th("Pear trials"), tags$th("N")),
      tags$th("Detected"), tags$th("Carryover favored"), tags$th("Unresolved"),
      tags$th("Fixed-rate or reset favored")))
    sources <- c("associability", "value", "reset")
    tagList(
      P("For your design, ", a$n, " participants with ", view_labels[[a$rec]], " analyzed, the
         percentages of the 400 experiments per process were:"),
      div(class = "scroll-x", tabindex = "0", role = "region", `aria-label` = "Results for your design",
        tags$table(class = "values rates", heads(FALSE),
          tags$tbody(lapply(sources, function(src) row(src, as.integer(a$n), a$rec))))),
      p(class = "table-note", "Detected: the 95% interval for the mean difference lies above
         zero. The last three columns give the decision of the comparison and add to 100% apart
         from rounding. Favoring associability carryover is correct only for responses generated
         by carried associability. Each row averages, with equal weight, four parameter sets:
         combinations of settings such as how fast the participants learn and how steep the
         response function is. It therefore describes a broader range of conditions than your
         case, which uses the base parameter set."),
      P("Your experiment ", if (design()$effect[["detected"]] == 1) "detected" else "did not
         detect", " a positive difference, and its comparison ",
         decision_text[[design()$decision$estimated]], "."),
      tags$details(class = "formula-details",
        tags$summary("All six designs"),
        div(class = "scroll-x", tabindex = "0", role = "region", `aria-label` = "All designs",
          tags$table(class = "values rates", heads(TRUE),
            tags$tbody(unlist(lapply(sources, function(src) lapply(c(160L, 40L), function(n)
              lapply(c("full", "early", "late"), function(view) row(src, n, view, design = TRUE)))),
              recursive = FALSE)))),
        p(class = "table-note", "Supplementary Table S2 of the tutorial reports the same
          percentages.")))
  })

  e4_choices <- c(detect = "Detecting a B–D difference.",
                  identify = "Identifying that it came from carried associability.",
                  same = "Both are about equally easy.")
  e4_items <- list(item("which", "With your design, which is easier when the responses were
    generated by carried associability?", e4_choices))
  e4_text <- function() {
    a <- answers$e_design
    mine <- rates_for("associability", as.integer(a$n), a$rec)
    full <- rates_for("associability", 160L, "full")
    late <- rates_for("associability", 160L, "late")
    small <- rates_for("associability", 40L, "full")
    paste0("With your design, a positive difference generated by carried associability is
      detected in ", pct(mine$detected), " of the experiments, but associability carryover is
      favored in only ", pct(mine$carry), ".",
      if (!(a$n == "160" && a$rec == "full")) paste0(" With 160 participants and all ten pear
      trials, the percentages are ", pct(full$detected), " and ", pct(full$carry), "."),
      " With 160 participants
      and only pear trials 8–10, associability carryover is favored in ", pct(late$carry), ", and
      a candidate without it is wrongly favored in ", pct(late$no_carry), ", because by those
      trials the alternatives can imitate the generating process closely. With 40 participants
      and all ten pear trials, associability carryover is favored in ", pct(small$carry), ",
      more often than with 160 participants and pear trials 8–10, although 800 responses are
      analyzed against 960.")
  }
  ask_server("e4", input, output, answers, e4_items,
    feedback = function(a) tagList(
      if (a$which != "detect") p("Detecting a difference was the easier task under every
        design."),
      p(e4_text())),
    on_submit = function(a) add_note("Step 5", "Detecting and identifying", e4_items[[1]]$label,
      e4_choices[[a$which]], result = e4_text(), settings = design_set(),
      open = "If all the candidates share a mistaken assumption, for example about the starting values or the response function, can choosing the best of them test it?"))

  # Trying another design or case, or starting the inquiry again, clears the
  # answers but keeps the notes.
  list(case = case, design = design, design_set = design_set, score_sentence = score_sentence,
       effect_text = effect_text,
       reset = function() clear_answers(answers, c("e_design", "e1", "e2", "e3", "e4")))
