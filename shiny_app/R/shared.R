# Step 6: checking what the candidates share (Section 7)
# The restricted comparison with g_V fixed at zero, the prediction that all its
# candidates share (Box 6) and the first-response check, the process that
# generated the reader's case, a difference that comes from responding, and
# the statements the reader would report. Uses the case and design chosen in
# Step 5.

shared_ui <- function() scene("scene-6", "6", "Checking what the candidates share",
  "output.done_e4", "done_f5",
  paste0("Fixing ", gV, " at zero made the comparison more decisive, but it also favored associability carryover in nearly all experiments generated by carried learned value. The first responses test a prediction that all the candidates share, which no ranking of them can test."),
  h3("When a restricted comparison favors the wrong explanation"),
  P("In Step 5, every candidate could estimate the carryover of learned value, ", gV, ". This
     gave the fixed-rate and reset candidates a way to produce a difference between ", B_gloss,
     " and ", D_gloss, ". We might instead argue that the pear is a new outcome and fix ", gV,
     " at zero in every candidate. This is the restricted comparison."),
  div(class = "question", uiOutput("f1")),
  conditionalPanel("output.done_f1",
    uiOutput("f1_result"),
    fig("f_scores_zero", "170px"),
    uiOutput("f1_rates"),
    h3("A prediction that ranking cannot test"),
    div(class = "question", uiOutput("f2"))),
  conditionalPanel("output.done_f2",
    uiOutput("f_first"),
    uiOutput("f3_box")),
  conditionalPanel("output.f_revealed",
    h3("What produced these responses?"),
    uiOutput("f_truth"),
    fig("f_contrast_truth", "260px"),
    uiOutput("f_check_rates"),
    h3("When the difference comes from responding"),
    p("In Step 4 we assumed that the same learned value gives the same probability of a yes
       response to B and to D. A participant might, however, be more reluctant to answer yes to
       B than to D at the same learned value. B could then receive fewer yes responses than D
       without having learned less. Counterbalancing the physical lights does not remove such a
       tendency if it follows the training role rather than the physical light."),
    p("The tutorial examined this possibility in a separate set of simulated experiments. The
       responses were generated by Rescorla–Wagner, with no carryover of learned value and a
       lower response intercept for B than for D, that is, a lower baseline tendency to answer
       yes to B, so a yes is less likely for B at the same learned value. The resulting difference in yes probability is small on the first pear
       trials, largest around the sixth, and smaller again as yes responses to both lights
       become common."),
    div(class = "question", uiOutput("f4"))),
  conditionalPanel("output.done_f4",
    h3("What would you report?"),
    div(class = "question", uiOutput("f5")),
    conditionalPanel("output.done_f5",
      settled(paste0("When ", gV, " was fixed at zero in every candidate, the comparison became
               more decisive but favored associability carryover even when carried learned value
               had generated the responses. The first-response check tested a prediction that all
               the candidates shared, and it flagged nearly all of those wrong conclusions."),
              "A rejection does not show which shared assumption failed. Before an experiment,
               we can ask whether the candidates represent each plausible source of a difference
               and whether the experiment records responses that can check their shared
               predictions."),
      aside("Section 7, Equation 8, Figure 9, Table 9 and Box 6."),
      p(actionLink("e_again", "Try another case or design"),
        span(class = "muted", " (this clears your answers in Steps 5 to 7 and keeps your notes)"))))
)


shared_server <- function(input, output, answers, add_note, flag, experiment) {
  case <- experiment$case
  design <- experiment$design
  design_set <- experiment$design_set
  score_sentence <- experiment$score_sentence

  # The restricted comparison
  f1_choices <- c(
    carry = "Only the carryover candidate, through the associability carried over from the compound trials.",
    all = "All three, because each can still fit its learning rates to the responses.",
    none = "None of them, because all three now start B and D at zero.")
  f1_items <- list(item("which", paste0("With ", gV, " fixed at zero in every candidate, which
    candidates can still explain a systematic B&ndash;D difference?"), f1_choices))
  f1_text <- "The fixed-rate and reset candidates can then no longer explain a systematic B–D
    difference, because both lights start the pear trials at zero and neither candidate ties a
    learning rate to the training role. The carryover candidate still can, through the
    associability difference carried over from the compound trials."
  ask_server("f1", input, output, answers, f1_items, button = "Run the restricted comparison",
    feedback = function(a) tagList(
      if (a$which == "all") p("With no carried-over value, the fixed-rate and reset candidates
        have no way to make B and D differ systematically.")
      else if (a$which == "none") p("The carryover candidate can still explain a difference."),
      p(f1_text)),
    on_submit = function(a) add_note("Step 6", "The restricted comparison", f1_items[[1]]$label,
      f1_choices[[a$which]],
      result = paste0(f1_text, " Score differences for your case are as follows. ",
                      score_sentence("zero")),
      settings = paste0(design_set(), "; ", policy_label[["zero"]])))
  output$f1_result <- renderUI({
    req(answers$f1)
    d <- design()
    tagList(
      P("For your case and design, with ", gV, " fixed at zero, the score differences are as
        follows. ", score_sentence("zero")),
      P("With ", gV, " estimated, in Step 5, the comparison ", decision_text[[d$decision$estimated]],
        "."),
      p(class = "muted", "The study ran this comparison for two processes, with 160
        participants and all ten pear trials. The comparisons for the other processes and designs
        were run with the study's code when this page was built."))
  })
  output$f_scores_zero <- renderPlot({ req(answers$f1); plot_scores(design()$scores$zero) })
  output$f1_rates <- renderUI({
    req(answers$f1)
    z <- function(src) zero_rates$carry[zero_rates$scenario == src]
    est <- function(src) rates$carry[rates$scenario == src & rates$n == 160 & rates$view == "full"]
    P("Across the tutorial's 400 experiments with 160 participants and all ten pear trials, the
       restricted comparison favored associability carryover in ", pct(z("associability")),
       " of those generated by carried associability, against ", pct(est("associability")),
       " when ", gV, " was estimated. It was more decisive. It also favored associability
       carryover in ", pct(z("value")), " of those generated by carried learned value, against ",
       pct(est("value")), " when ", gV, " was estimated, and for those experiments the
       conclusion is wrong. The mistake is in the candidate set, because none of the candidates
       can represent the source that generated the difference.")
  })

  # Box 6: the shared prediction
  first_choices <- c(
    equal = "The same probability of a yes for B and D.",
    carry = "A higher probability for D, but only in the carryover candidate.",
    depends = "It depends on the fitted parameters.")
  rank_choices <- c(no = "No. Every candidate makes the same prediction.",
                    yes = "Yes. The best-ranked candidate shows whether the prediction holds.")
  f2_items <- list(
    item("first", "Every candidate in the restricted comparison starts B and D with zero learned
      value for the pear and uses the same response function for both lights. Each light's first
      response comes before the pear has appeared with that light. What must all three
      candidates predict about the probabilities that the first responses to B and D are
      yes?", first_choices),
    item("rank", "Could a ranking of the candidates test that prediction?", rank_choices))
  f2_text <- "These conditions make the first-response probabilities equal under any shared
    response function, whatever associabilities or learning rates the lights bring: both equal
    the response function's value at zero. In the models, pear trials with one light leave the
    other unchanged, so the equality holds for each participant, whichever light's pear trials
    come first. Because every candidate makes this prediction, ranking the candidates cannot
    test it. It can be checked directly against the first responses."
  ask_server("f2", input, output, answers, f2_items,
    reason = "Which responses could you examine directly? (optional)",
    button = "Check the first responses",
    feedback = function(a) tagList(
      if (a$first == "carry") p("The carryover candidate predicts equal first responses too.
        Carried associability changes learning from the pear. It does not give a light a larger
        starting value.")
      else if (a$first == "depends") p("Every choice of parameters keeps this equality while the
        starting values are zero and the response function is shared."),
      if (a$rank == "yes") p("A ranking compares the candidates with one another. A prediction
        that all of them make cannot favor any one of them, so the ranking cannot test it."),
      p(f2_text)),
    on_submit = function(a) add_note("Step 6", "What all the candidates predict",
      f2_items[[1]]$label, paste0(first_choices[[a$first]], " Ranking: ", rank_choices[[a$rank]],
        if (nzchar(a$reason)) paste0(" To examine: ", a$reason)),
      result = "Equal first-response probabilities for B and D, which ranking cannot test.",
      settings = paste0(design_set(), "; ", policy_label[["zero"]])))

  # The first-response check
  output$f_first <- renderUI({
    req(answers$f2)
    f <- design()$first
    if (is.null(f)) return(tagList(
      P("Your analysis kept pear trials ", min(design()$cols), "&ndash;", max(design()$cols),
        ". The check needs each participant's first response to B and first response to D, so it
        cannot be made with the responses you kept. A design that includes the first pear trial
        would keep that information."),
      p(class = "muted", "You can still see below how this case was generated.")))
    tagList(
      p("Look at each participant's first response to B and first response to D:"),
      tags$table(class = "values",
        tags$tbody(
          tags$tr(tags$td("Yes to D, no to B"), tags$td(f$d_only)),
          tags$tr(tags$td("Yes to B, no to D"), tags$td(f$b_only)),
          tags$tr(tags$td("The same response to both"), tags$td(f$n - f$d_only - f$b_only)))),
      p(paste0("These are the same responses as the first point in the plot of Step 5: (",
        f$d_only, " − ", f$b_only, ")/", f$n, " = ", num((f$d_only - f$b_only) / f$n), ".
        Participants who gave the same response to both lights carry no information about a
        difference. Under equality, the two kinds of differing responses should be equally
        common. We use an exact one-sided paired test (McNemar's test) to calculate how often
        equality would produce at least this many yes-to-D-only responses among the participants
        who responded differently. That probability is the p-value: ", p_text(f$p), ". At the .05
        level, the check rejects equality if p < .05.")),
      p(class = "muted", "This check was added to the tutorial's study after the main
        evaluation, and it was not part of the decision rule."))
  })
  f3_choices <- c(
    disagree = "The responses disagree with a prediction that all the candidates share.",
    consistent = "The check found no clear evidence against the shared prediction.",
    value = "Learned values for the apple carried over to the pear.")
  f3_items <- list(item("h", "What does this check tell you?", f3_choices))
  output$f3_box <- renderUI({
    req(answers$f2)
    if (is.null(design()$first)) return(NULL)
    div(class = "question", uiOutput("f3"))
  })
  ask_server("f3", input, output, answers, f3_items,
    feedback = function(a) {
      rejects <- design()$first$p < .05
      tagList(
        p(if (rejects) "At the .05 level, the one-sided test rejects equal first-response
          probabilities in the direction of more yes responses to D. That is evidence against a
          prediction that all three candidates share."
          else "The one-sided test finds no clear evidence of more yes responses to D on the
          first pear trial at the .05 level. That does not show that the two probabilities are
          equal."),
        if (a$h == "consistent" && rejects) p("You chose no clear evidence, but this test
          rejects the shared prediction. A ranking of the candidates cannot reveal that mismatch,
          because all three predict the same equality."),
        if (a$h == "disagree" && !rejects) p("You chose a disagreement, but this check did not
          find clear evidence in that direction. The counts can differ without meeting the test
          criterion."),
        if (a$h == "value") p("The check cannot show that learned values carried over. It tests
          the shared prediction without identifying the source of a difference."),
        p("If the check rejects equality, learned values for the apple may carry over, the two
           lights may have different response functions, or something the models leave out may
           affect the two lights differently."))
    },
    on_submit = function(a) {
      f <- design()$first
      add_note("Step 6", "The first-response check", "What does the first-response check show?",
        f3_choices[[a$h]],
        result = paste0(f$d_only, " participants said yes to D only and ", f$b_only,
                        " yes to B only (", p_text(f$p), ")."),
        settings = paste0(design_set(), "; first responses to B and D, exact one-sided paired test at the .05 level"),
        open = "If equality is rejected, which shared assumption failed: the starting values, the response function, or something the models leave out?")
    })

  # The reveal comes after the first-response check, or after the question
  # about the shared prediction when the responses lack the first pear trial.
  flag("f_revealed", function() !is.null(answers$f3) ||
         (!is.null(answers$f2) && is.null(design()$first)))

  # The generating process
  both_decisions <- function(d) if (d$decision$zero == d$decision$estimated)
    paste0("With ", gV, " estimated and with it fixed at zero, the comparison ",
           decision_text[[d$decision$zero]])
  else paste0("With ", gV, " estimated, the comparison ", decision_text[[d$decision$estimated]],
              ", and with it fixed at zero it ", decision_text[[d$decision$zero]])
  group_text <- function(cs, d) {
    diffs <- participant_differences(cs, d$cols)
    m <- tapply(diffs$difference, diffs$group, mean)
    paste0("The generating model also made light 1 more salient than light 2, so light 1
      learned faster in either role. This is the difference between the two groups in the dot
      plot of Step 5: where light 1 served as B, the mean D-minus-B difference was ",
      num(m[["1"]]), ", and where light 2 served as B it was ", num(m[["-1"]]), ".")
  }
  output$f_truth <- renderUI({
    cs <- case(); d <- design(); g <- cs$generating; a <- answers$e_design
    # The carried-learned-value case with 160 participants is the first such
    # experiment in the base parameter set. With all ten pear trials, its
    # restricted comparison favored associability carryover, and the note below
    # is shown for this design only.
    chosen <- a$rec == "full" && a$n == "160"
    tagList(
      switch(cs$source,
        value = tagList(
          P("<b>Carried learned value.</b> ", set_labels[[a$set]], " was generated by ", RW, ",
             with fixed learning rates and ", round(100 * g$g_value), "% of each light's learned
             value for the apple carried over to the pear. With ", gV, " fixed at zero, none of
             the three candidates can represent this process, and the comparison ",
             decision_text[[d$decision$zero]],
             if (d$decision$zero == "carry") ", because the carryover candidate is the only one
               that can produce a systematic difference at all" else "",
             ". With ", gV, " estimated, it ", decision_text[[d$decision$estimated]], "."),
          if (chosen) tagAppendAttributes(P("This case is the first experiment of this kind in
             the base parameter set, so it was not chosen for its result."), class = "muted")),
        associability = P("<b>Carried associability.</b> ", set_labels[[a$set]], " was generated
           by the adaptive model, with ", round(100 * g$g_alpha), "% of the earlier change in
           associability carried over to the pear trials and no carryover of learned value. ",
           both_decisions(d), ". Favoring associability carryover is correct here."),
        reset = P("<b>Reset associability.</b> ", set_labels[[a$set]], " was generated by the
           adaptive model with no carryover of either kind, so B and D entered the pear trials in
           the same state, apart from the counterbalanced difference between the physical lights. ",
           both_decisions(d), ". There is no systematic B&ndash;D difference to find. Favoring
           associability carryover would be a mistake here, and favoring a candidate without it
           does not show which alternative generated the responses.")),
      P(group_text(cs, d)),
      p(class = "muted", "The gray line below is the generating model's difference in yes
        probability on each pear trial, averaged over your participants."),
      if (cs$source == "value") p(class = "muted", "It rises over the first pear trials,
        although the gap in learned value is largest before the first pear trial and shrinks from
        then on (Step 3), because the sigmoid is flat at low learned values (Step 4). What marks
        carried-over value is that the difference is already above zero on the first pear
        trial."))
  })
  output$f_contrast_truth <- renderPlot({ req(answers$f2); plot_contrast(case(), design(), truth = TRUE) })
  output$f_check_rates <- renderUI({
    fr <- function(src, col) first_rates[[col]][first_rates$scenario == src]
    P("Across the tutorial's 400 experiments per process, each with 160 participants, the
       first-response check rejected equality in ", pct(fr("associability", "rejection_160")),
       " of those generated by carried associability. There the first-response probabilities are
       equal, so these rejections are false alarms. It rejected equality in ",
       pct(fr("reset", "rejection_160")), " of those generated by reset associability, in ",
       pct(fr("value", "rejection_160")), " of those generated by carried learned value, and in ",
       pct(fr("value", "rejection_given_carry")), " of the ",
       round(fr("value", "carry_preferred") * fr("value", "repetitions")), " in which the
       restricted comparison had wrongly favored associability carryover. The check would have
       flagged nearly all of the wrong conclusions.")
  })

  # A difference that comes from responding
  f4_choices <- c(
    learning = "As a difference in learning: carried-over learned value or associability carryover.",
    responding = "As a difference in responding.",
    unfit = "They cannot fit the responses at all.")
  f4_items <- list(item("explain", "Candidates that use one response function for both lights are
    fitted to these responses. How will they explain B's fewer yes responses?", f4_choices))
  f4_text <- function() {
    shared <- response_rates[response_rates$policy == "value_allowed", ]
    own <- response_rates[response_rates$policy == "response_allowed", ]
    paste0("Candidates with one response function for both lights can explain the difference
      only as learning. The fixed-rate and reset candidates explain it through carried-over
      learned value, and the carryover candidate mainly through associability carryover. Across
      400 experiments, each with 160 participants and all ten pear trials analyzed, a positive
      B–D difference was detected in ", pct(shared$detected), ". The carryover candidate ranked
      first, with the highest held-out score, in ", pct(shared$ranked_carry), ", but passed the
      decision margin in only ", pct(shared$carry), ", and ", pct(shared$unresolved), " of the
      comparisons were unresolved. The first-response check rejected equality in only ",
      pct(first_rates$rejection_160[first_rates$scenario == "response"]), ", because most
      participants said no to both lights at first.")
  }
  f4_own_text <- function() {
    own <- response_rates[response_rates$policy == "response_allowed", ]
    paste0("When every candidate could also give B its own response intercept, associability
      carryover was never favored. Of the comparisons, ", pct(own$unresolved), " were
      unresolved, and the other ", pct(own$no_carry), " favored a candidate without associability
      carryover. The tutorial specified this lower response intercept to ask whether candidates
      with one response function would attribute the difference to learning. Real participants
      are not known to respond this way.")
  }
  ask_server("f4", input, output, answers, f4_items,
    feedback = function(a) tagList(
      if (a$explain == "responding") p("A candidate can attribute the difference to responding
        only if it allows B and D different response functions, and these candidates do not.")
      else if (a$explain == "unfit") p("They fit the responses, by attributing the difference to
        learning."),
      p(f4_text()),
      p(f4_own_text())),
    on_submit = function(a) add_note("Step 6", "A difference that comes from responding",
      f4_items[[1]]$label, f4_choices[[a$explain]], result = paste(f4_text(), f4_own_text()),
      settings = "Generated by Rescorla–Wagner with g_V = 0 and a lower response intercept for B; 400 experiments with 160 participants and all ten pear trials"))

  # What would be reported
  statements <- reactive({
    d <- design()
    est <- d$decision$estimated
    list(
      list(text = "The mean D-minus-B difference in yes responses is positive, with a 95% interval above zero.",
           ok = d$effect[["detected"]] == 1,
           why = paste0("The mean difference is ", num(d$effect[["estimate"]]), " (95% interval ",
                        num(d$effect[["lower"]]), " to ", num(d$effect[["upper"]]), "), and the
                        interval ", if (d$effect[["detected"]] == 1) "lies above zero." else
                        "does not lie above zero.")),
      list(text = paste0("With ", gV, " estimated, the comparison reached a preference for or against associability carryover."),
           ok = est != "unresolved",
           why = paste0("With ", gV, " estimated, the comparison ", decision_text[[est]],
                        ", under the rule fixed before the analysis.")),
      list(text = "The comparison of candidates showed which process generated the responses.",
           ok = FALSE,
           why = "Held-out scores measure how well the supplied candidates predict new participants. They cannot test assumptions that every candidate shares, and the generating process may be missing from the candidates."),
      list(text = paste0("Fixing ", gV, " at zero made the comparison more trustworthy, because it reached a decision more often."),
           ok = FALSE,
           why = paste0("A decision is not the same as a correct decision. With ", gV, " fixed at zero, none of the candidates can represent carried learned value, so the restricted comparison favored associability carryover in ",
                        pct(zero_rates$carry[zero_rates$scenario == "value"]),
                        " of the experiments generated by that process.")),
      list(text = "The first responses disagree with a prediction that all the candidates of the restricted comparison share.",
           ok = !is.null(d$first) && d$first$p < .05,
           why = if (is.null(d$first)) "Your analysis did not keep the first pear trial, so the check could not be made."
                 else if (d$first$p < .05) paste0("The one-sided check rejected equal first-response probabilities (", p_text(d$first$p), "). That is evidence that a shared assumption failed. It does not show which one.")
                 else paste0("The check found no clear evidence against equal first-response probabilities (", p_text(d$first$p), ").")))
  })
  output$f5 <- renderUI({
    st <- statements()
    if (is.null(answers$f5)) {
      tagList(
        checkboxGroupInput("f5_pick", span(class = "item-label", "Which statements would you
          include in a report of this experiment? Select all that your results support."),
          width = "100%",
          choiceNames = lapply(seq_along(st), function(i) HTML(paste0(i, ". ", st[[i]]$text))),
          choiceValues = as.character(seq_along(st))),
        actionButton("f5_go", "Compare with the results", class = "btn-submit"))
    } else {
      picked <- answers$f5$picked
      tagList(lapply(seq_along(st), function(i) {
        s <- st[[i]]; mine <- as.character(i) %in% picked
        div(class = "statement",
          P("<b>", i, ". ", s$text, "</b>"),
          p(class = "answered-label", paste0(if (mine) "You selected this. " else "You left this out. ",
            if (s$ok) "Your results support it." else "Your results do not support it.")),
          tagAppendAttributes(P(s$why), class = if (mine == s$ok) "agree" else "disagree"))
      }))
    }
  })
  observeEvent(input$f5_go, {
    if (!is.null(answers$f5)) return()
    st <- statements()
    picked <- if (is.null(input$f5_pick)) character(0) else input$f5_pick
    answers$f5 <- list(picked = picked)
    judged <- vapply(seq_along(st), function(i) paste0(i, ". ", st[[i]]$text, " ",
      if (st[[i]]$ok) "Supported. " else "Not supported. ", st[[i]]$why), "")
    add_note("Step 6", "What you would report", "Which statements would you include in a report?",
      paste0("Selected ", if (!length(picked)) "none" else
               paste(if (length(picked) == 1) "statement" else "statements",
                     paste(picked, collapse = ", ")), "."),
      result = paste0(paste(judged, collapse = " "), " Generating process: ",
                      process_names[[case()$source]], "."),
      settings = paste0(design_set(), "; ", generating_set()))
  })
  generating_set <- function() {
    g <- case()$generating
    # The symbols of Supplement S2; g_V, g_alpha and eta are printed without a
    # leading zero.
    symbols <- c(mu = "mu", spread = "tau", cue = "d", intercept = "b",
                 log_slope = "log gamma", g_value = "g_V", eta = "eta", g_alpha = "g_alpha",
                 history_intercept = "b_B")
    printed <- vapply(names(g), function(nm) {
      x <- format(g[[nm]], digits = 15, trim = TRUE)
      if (nm %in% c("g_value", "g_alpha", "eta")) sub("^0[.]", ".", x) else x
    }, "")
    paste0("generating parameters: ", paste(symbols[names(g)], printed, sep = " = ", collapse = "; "),
      "; starting learning rate r = .5 * logistic(mu + tau * z + x * d), z = -1 or +1 with equal",
      " probability, x = +1 for light 1 and -1 for light 2; Rescorla–Wagner learning rate = r;",
      " adaptive salience S = 2r with starting associability .5",
      "; learned values for the pear start at g_V times those for the apple; associabilities at",
      " .5 + g_alpha * (associability at the end of the compound trials - .5)",
      "; first-response check: exact one-sided paired test, p < .05",
      "; repeated-experiment percentages average four parameter sets, 100 experiments each per design")
  }

  # Trying another design or case, or starting the inquiry again, clears the
  # answers but keeps the notes.
  list(reset = function() clear_answers(answers, c("f1", "f2", "f3", "f4", "f5")))
}
