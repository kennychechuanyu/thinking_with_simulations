# Figure 9 (Sections 7.1 and 7.2): with the carryover of learned value g_V
# fixed at zero in every candidate, (a) the evidence on which the restricted
# comparison decides, with an outline for the same experiments analyzed with
# g_V estimated, and (b) the first-response check, the difference in first
# responses with the decision of the exact paired test. Reads results.csv and
# initial_response_checks.csv, which
# analysis/section7_first_response_and_bounds.R writes. The numbers that the
# paper prints about the figure are checked against the data drawn and against
# the macros in results/section6/section6_numbers.tex.
#   Rscript analysis/section7_fig09_shared_prediction.R

if (!file.exists("R/models.R")) stop("Run this script from the repository root.")
source("R/figure_style.R")
library(patchwork)

# The evidence of each experiment, as in Figure 8: the carryover candidate's
# held-out score minus each alternative's, divided by its standard error, and
# the smaller of the two. A difference of zero with a standard error of zero
# counts as zero. The decision rule favors associability carryover above 2 and
# another candidate below -2.
results <- read.csv("results/section6/results.csv")
standardized <- function(difference, se) ifelse(difference == 0 & se == 0, 0, difference / se)
results$evidence <- pmin(standardized(results$carry_vs_fixed, results$carry_vs_fixed_se),
                         standardized(results$carry_vs_reset, results$carry_vs_reset_se))
decision_of <- function(evidence) {
  ifelse(evidence > 2, "carry", ifelse(evidence < -2, "no_carry", "unresolved"))
}

# The restricted analyses (g_V = 0, policy value_zero) with the first-response
# test of each experiment, and the same experiments analyzed with g_V estimated
# (policy value_allowed).
first_responses <- read.csv("results/section6/initial_response_checks.csv")
restricted <- merge(results[results$policy == "value_zero", ],
                    first_responses[c("id", "discordant_control", "discordant_blocked",
                                      "initial_p", "initial_rejection")], by = "id")
process_names <- c(associability = "Carried associability", value = "Carried learned value")
estimated <- results[results$policy == "value_allowed" & results$n == 160 &
                       results$view == "full" & results$scenario %in% names(process_names), ]

# The first-response difference of each experiment: participants whose first
# response is yes to D but not to B, minus those with the reverse pattern,
# divided by the square root of their sum. The paired test uses only these
# participants.
discordant <- restricted$discordant_control + restricted$discordant_blocked
restricted$first_difference <- (restricted$discordant_control - restricted$discordant_blocked) /
  sqrt(discordant)

share <- function(process, decision) {
  mean(restricted$decision[restricted$scenario == process] == decision)
}
rejected <- sapply(names(process_names), function(process)
  mean(restricted$initial_rejection[restricted$scenario == process]))
# Among the experiments generated by carried learned value in which the
# restricted comparison wrongly favors associability carryover.
wrong_wins <- restricted$scenario == "value" & restricted$decision == "carry"
rejected_wrong_wins <- mean(restricted$initial_rejection[wrong_wins])
percent <- function(x) sprintf("%.1f%%", 100 * x)

# One row per generating process, and a third row for the experiments generated
# by carried learned value in which the comparison in panel a wrongly favors
# associability carryover. Panel a has nothing to draw in the third row.
rows <- data.frame(
  label = c(unname(process_names), "where (a) is wrong"),
  label_x = c(0, 0, .12),
  y = -(1:3),
  carry = c(share("associability", "carry"), share("value", "carry"), NA),
  unresolved = c(share("associability", "unresolved"), share("value", "unresolved"), NA),
  no_carry = c(share("associability", "no_carry"), share("value", "no_carry"), NA),
  rejected = c(rejected[["associability"]], rejected[["value"]], rejected_wrong_wins),
  experiments = c(sum(restricted$scenario == "associability"),
                  sum(restricted$scenario == "value"), sum(wrong_wins))
)
in_row <- list(restricted$scenario == "associability", restricted$scenario == "value", wrong_wins)

# Both panels count experiments in bins of half a standard error on the same
# axis. Bin edges fall at -2 and 2, so in panel a the shades give the shares of
# the decisions (checked below).
axis_limits <- c(-6, 10)
breaks <- seq(axis_limits[1], axis_limits[2], .5)
count_bins <- function(values) as.numeric(table(cut(values, breaks)))
bins <- function(i, ...) {
  data.frame(row = i, y = rows$y[i], xmin = head(breaks, -1), xmax = breaks[-1], ...)
}
# Panel a: the restricted evidence, shaded by the decision of each bin, and the
# evidence with g_V estimated.
restricted_bins <- do.call(rbind, lapply(1:2, function(i)
  bins(i, count = count_bins(restricted$evidence[in_row[[i]]]))))
restricted_bins$decision <- factor(
  decision_of((restricted_bins$xmin + restricted_bins$xmax) / 2),
  levels = c("carry", "unresolved", "no_carry"))
estimated_bins <- do.call(rbind, lapply(1:2, function(i)
  bins(i, count = count_bins(estimated$evidence[estimated$scenario == names(process_names)[i]]))))
# Panel b: the first-response difference, with the experiments in which the
# test rejects equality at the bottom of each bar.
first_bins <- do.call(rbind, lapply(1:3, function(i) {
  d <- restricted[in_row[[i]], ]
  all <- count_bins(d$first_difference)
  rejected_count <- count_bins(d$first_difference[d$initial_rejection])
  bins(i, rejected = rejected_count, kept = all - rejected_count)
}))
# The tallest bin of either panel fills 85% of the space between two rows.
bar_scale <- .85 / max(restricted_bins$count, estimated_bins$count,
                       first_bins$rejected + first_bins$kept)
base <- function(y) y - .42

ink <- paper_colours[["ink"]]
grey <- paper_colours[["grey"]]
# The column heading and the panel titles share one line above the first row.
header_y <- max(rows$y) + 1.1
y_scale <- scale_y_continuous(limits = c(min(rows$y) - .5, header_y + .3),
                              expand = expansion(mult = 0))
x_scale <- scale_x_continuous(limits = axis_limits, breaks = c(-4, -2, 0, 2, 4, 6, 8),
                              labels = c("−4", "−2", "0", "2", "4", "6", "8"),
                              expand = expansion(mult = 0))
# Each panel has its legend below it, starting at its left edge, and the two
# legends are aligned at the top.
theme_figure9 <- theme_paper() +
  theme(axis.line.y = element_blank(), axis.ticks.y = element_blank(),
        axis.text.y = element_blank(), axis.title.y = element_blank(),
        axis.title.x = element_text(size = 9.5, margin = margin(t = 5)),
        legend.position = "bottom", legend.justification = c(0, 1),
        legend.box = "vertical", legend.box.just = "left", legend.spacing.y = unit(2, "pt"),
        legend.key.size = unit(8, "pt"), legend.key.width = unit(14, "pt"),
        legend.text = element_text(size = 9, colour = ink, margin = margin(l = 3, r = 10)),
        legend.margin = margin(0, 0, 0, 0))
panel_title <- function(label) {
  annotate("text", x = axis_limits[1], y = header_y, label = label, hjust = 0,
           size = 10 / .pt, fontface = "bold", colour = ink)
}
baselines <- function(n) {
  geom_segment(data = rows[seq_len(n), ], aes(x = axis_limits[1], xend = axis_limits[2],
                                              y = base(y), yend = base(y)),
               colour = "#BDBDBD", linewidth = .25)
}
zero_line <- function(n) {
  annotate("segment", x = 0, xend = 0, y = -n - .5, yend = -.5, colour = "#9E9E9E",
           linewidth = .3, linetype = "22")
}

# The row labels, placed in inches from the left.
row_labels <- ggplot(rows) +
  geom_text(aes(label_x, y, label = label), hjust = 0, size = text_size, colour = ink) +
  annotate("text", x = 0, y = header_y, hjust = 0, label = "Generating process",
           size = text_size, colour = grey) +
  scale_x_continuous(limits = c(0, 1.45), expand = expansion(mult = 0)) + y_scale +
  coord_cartesian(clip = "off") +
  theme_void() + theme(plot.margin = margin(4, 0, 4, 4))

# The outline follows the tops of the bins with g_V estimated and drops to the
# baseline on either side.
outline <- do.call(rbind, lapply(split(estimated_bins, estimated_bins$row), function(d) {
  keep <- d$count > 0 | c(d$count[-1] > 0, FALSE) | c(FALSE, head(d$count, -1) > 0)
  d <- d[keep, ]
  data.frame(row = d$row[1], x = c(rbind(d$xmin, d$xmax)),
             top = rep(base(d$y) + bar_scale * d$count, each = 2))
}))
decisions <- c(carry = "Associability carryover favored", unresolved = "Unresolved",
               no_carry = "Another candidate favored")
panel_a <- ggplot() +
  geom_rect(data = restricted_bins[restricted_bins$count > 0, ],
            aes(xmin = xmin, xmax = xmax, ymin = base(y), ymax = base(y) + bar_scale * count,
                fill = decision)) +
  geom_path(data = outline, aes(x, top, group = row, linetype = "estimated"), colour = ink,
            linewidth = .35) +
  baselines(2) + zero_line(2) +
  annotate("segment", x = c(-2, 2), xend = c(-2, 2), y = -2.5, yend = -.5, colour = ink,
           linewidth = .3) +
  panel_title("(a)  Restricted comparison") +
  scale_fill_manual(values = c(carry = paper_colours[["carry"]], unresolved = "#D0D0D0",
                               no_carry = "#5E5E5E"), labels = decisions, name = NULL,
                    guide = guide_legend(ncol = 1, order = 1)) +
  scale_linetype_manual(values = c(estimated = "solid"), name = NULL,
                        labels = expression(paste("With ", italic(g)[V], " estimated")),
                        guide = guide_legend(order = 2)) +
  x_scale + y_scale + coord_cartesian(clip = "off") +
  labs(x = "Advantage of the carryover\ncandidate, in standard errors") +
  theme_figure9 + theme(plot.margin = margin(4, 16, 4, 4))

first_bars <- rbind(
  transform(first_bins, test = "rejected", ymin = base(y), ymax = base(y) + bar_scale * rejected),
  transform(first_bins, test = "kept", ymin = base(y) + bar_scale * rejected,
            ymax = base(y) + bar_scale * (rejected + kept)))
first_bars$test <- factor(first_bars$test, levels = c("rejected", "kept"))
panel_b <- ggplot() +
  geom_rect(data = first_bars[first_bars$ymax > first_bars$ymin, ],
            aes(xmin = xmin, xmax = xmax, ymin = ymin, ymax = ymax, fill = test)) +
  baselines(3) + zero_line(3) +
  panel_title("(b)  Paired test of first responses") +
  scale_fill_manual(values = c(rejected = "#5E5E5E", kept = "#D0D0D0"), name = NULL,
                    labels = c(rejected = "Equality rejected", kept = "Not rejected"),
                    guide = guide_legend(ncol = 1)) +
  x_scale + y_scale + coord_cartesian(clip = "off") +
  labs(x = "First responses, D minus B,\nin standard errors") +
  theme_figure9 + theme(plot.margin = margin(4, 8, 4, 4))

figure <- row_labels + panel_a + panel_b +
  plot_layout(widths = unit(c(1.45, 1, 1), c("in", "null", "null")))

cat(sprintf("Carryover favored with g_V = 0: carried associability %s, carried learned value %s\n",
            percent(share("associability", "carry")), percent(share("value", "carry"))))
cat(sprintf(paste0("First-response test rejects equality: carried associability %s, ",
                   "carried learned value %s (%s where carryover is wrongly favored)\n"),
            percent(rejected[["associability"]]), percent(rejected[["value"]]),
            percent(rejected_wrong_wins)))
cat(sprintf("Median evidence, g_V estimated and fixed at zero: %s %.1f and %.1f\n",
            process_names,
            sapply(names(process_names), function(p) median(estimated$evidence[estimated$scenario == p])),
            sapply(names(process_names), function(p) median(restricted$evidence[restricted$scenario == p]))),
    sep = "")
save_figure(figure, "fig09_shared_prediction", 7, 3.2)

# Numbers printed in the text, named by their macros in section6_numbers.tex.
macro_lines <- grep("^\\\\newcommand", readLines("results/section6/section6_numbers.tex"),
                    value = TRUE)
paper <- setNames(sub("^.*\\}\\{(.*)\\}$", "\\1", macro_lines),
                  sub("^\\\\newcommand\\{\\\\([A-Za-z]+)\\}.*$", "\\1", macro_lines))
# The share of each row's experiments in each shade of panel a.
shaded <- tapply(restricted_bins$count, list(restricted_bins$row, restricted_bins$decision), sum) /
  rows$experiments[1:2]
shaded[is.na(shaded)] <- 0

# Values reported in the paper
stopifnot(
  # Caption: all ten responses of 160 participants, 400 experiments per process
  restricted$n == 160, restricted$view == "full",
  table(restricted$scenario)[names(process_names)] == 400,
  # Caption: the outline shows the same simulated experiments with g_V
  # estimated, the first and seventh rows of Figure 8
  table(estimated$scenario)[names(process_names)] == 400,
  sapply(names(process_names), function(p) {
    setequal(restricted$seed[restricted$scenario == p], estimated$seed[estimated$scenario == p])
  }),
  # Panel a and the caption: the decision rule is a threshold on the evidence
  # drawn, every value lies within the axis, and no comparison favored an
  # alternative or failed, so each row is carryover favored and unresolved
  decision_of(restricted$evidence) == restricted$decision,
  c(restricted$evidence, estimated$evidence) > axis_limits[1],
  c(restricted$evidence, estimated$evidence) < axis_limits[2],
  !(restricted$decision %in% c("no_carry", "fit_problem")),
  abs(rows$carry[1:2] + rows$unresolved[1:2] - 1) < 1e-9, rows$no_carry[1:2] == 0,
  abs(shaded[, "carry"] - rows$carry[1:2]) < 1e-9,
  abs(shaded[, "unresolved"] - rows$unresolved[1:2]) < 1e-9,
  # Section 7.1: with g_V fixed at zero, the comparison is more decisive when
  # carried associability generated the responses
  median(restricted$evidence[restricted$scenario == "associability"]) >
    median(estimated$evidence[estimated$scenario == "associability"]),
  # Panel b: every experiment has a participant whose first responses differ,
  # every difference lies within the axis, and the shading is the decision of
  # the exact one-sided paired test on the counts drawn
  discordant > 0,
  restricted$first_difference > axis_limits[1], restricted$first_difference < axis_limits[2],
  abs(pbinom(restricted$discordant_control - 1, discordant, .5, lower.tail = FALSE) -
        restricted$initial_p) < 1e-12,
  restricted$initial_rejection == (restricted$initial_p < .05),
  tapply(first_bins$rejected, first_bins$row, sum) ==
    sapply(in_row, function(k) sum(restricted$initial_rejection[k])),
  # Caption: standard errors from the finite number of experiments are at most
  # StudyMaxMCSE percentage points for every rate drawn
  sqrt(c(rows$carry[1:2] * (1 - rows$carry[1:2]) / rows$experiments[1:2],
         rows$rejected * (1 - rows$rejected) / rows$experiments)) <=
    as.numeric(paper[["StudyMaxMCSE"]]) / 100,
  # Sections 7.1 and 7.2, Table 9 and the caption: the percentages drawn, as
  # printed
  sprintf("%.1f", 100 * share("associability", "carry")) == paper[["AssocOmittedCarry"]],
  sprintf("%.1f", 100 * share("value", "carry")) == paper[["ValueOmittedCarry"]],
  sprintf("%.1f", 100 * rejected[["associability"]]) == paper[["AssocInitialRejected"]],
  sprintf("%.1f", 100 * rejected[["value"]]) == paper[["ValueInitialRejected"]],
  sprintf("%.1f", 100 * rejected_wrong_wins) == paper[["ValueWrongFlagged"]],
  # Section 7.2 and the caption: the counts behind the last three percentages
  sum(restricted$initial_rejection[restricted$scenario == "value"]) == 379,
  sum(wrong_wins) == 380,
  sum(restricted$initial_rejection[wrong_wins]) == 362
)
