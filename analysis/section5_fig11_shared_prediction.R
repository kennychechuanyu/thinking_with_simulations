# Figure 11 (Section 5.6): with old-value carryover g_V fixed at zero in every
# candidate, how often the held-out comparison favors associability carryover,
# and how often the paired test of first responses rejects the equality all
# candidates predict. Reads results.csv and initial_response_checks.csv.
#   Rscript analysis/section5_fig11_shared_prediction.R

if (!file.exists("R/figure_style.R")) stop("Run this script from the repository root.")
source("R/figure_style.R")
library(patchwork)

# The restricted analyses (g_V = 0) with the first-response test of each experiment.
results <- read.csv("results/section5/results.csv")
first_responses <- read.csv("results/section5/initial_response_checks.csv")
restricted <- merge(results[results$policy == "value_zero", ],
                    first_responses[c("id", "initial_rejection")], by = "id")

process_labels <- c(associability = "Carried\nassociability",
                    value = "Value\ngeneralization")
share <- function(process, decision) {
  mean(restricted$decision[restricted$scenario == process] == decision)
}
rejected <- sapply(names(process_labels), function(process)
  mean(restricted$initial_rejection[restricted$scenario == process]))
# Among the value-generalization experiments in which carryover wrongly wins.
rejected_wrong_wins <- mean(restricted$initial_rejection[restricted$scenario == "value" &
                                                           restricted$decision == "carry"])
percent <- function(x) sprintf("%.1f%%", 100 * x)

ink <- paper_colours[["ink"]]
grey <- paper_colours[["grey"]]
theme_figure <- theme_paper(title_gap = 3) +
  theme(axis.text.y = element_text(lineheight = .95, hjust = 1),
        axis.title.x = element_text(margin = margin(t = 6)),
        axis.line.y = element_blank(), axis.ticks.y = element_blank(),
        plot.subtitle = element_text(lineheight = 1.1),
        plot.margin = margin(6, 12, 6, 6))
x_scale <- scale_x_continuous(limits = c(0, 1), breaks = c(0, .5, 1),
                              labels = c("0%", "50%", "100%"),
                              expand = expansion(mult = c(0, .01)))
y_scale <- scale_y_discrete(limits = rev(process_labels), labels = rev(process_labels),
                            expand = expansion(add = c(.8, .55)))
bar_height <- .5

# Panel a: the ranking favors carryover for records from either process. No
# comparison favored an alternative or failed (checked below), so the rest of
# each bar is unresolved.
decisions <- expand.grid(scenario = names(process_labels), decision = c("carry", "unresolved"),
                         stringsAsFactors = FALSE)
decisions$p <- mapply(share, decisions$scenario, decisions$decision)
decisions$process <- process_labels[decisions$scenario]
decisions$decision <- factor(decisions$decision, levels = c("unresolved", "carry"))
bar_labels <- data.frame(
  process = process_labels, x = .03,
  label = c(paste0(percent(share("associability", "carry")), " carryover (correct)"),
            paste0(percent(share("value", "carry")), " carryover (wrong)"))
)
panel_a <- ggplot(decisions, aes(p, process, fill = decision)) +
  geom_col(width = bar_height, colour = "white", linewidth = .25) +
  geom_text(data = bar_labels, aes(x, process, label = label), inherit.aes = FALSE,
            hjust = 0, size = text_size, colour = "white") +
  annotate("text", x = 1, y = 1 - bar_height / 2 - .15, label = "unresolved",
           hjust = 1, size = text_size, colour = grey) +
  scale_fill_manual(values = c(carry = paper_colours[["carry"]], unresolved = "#D0D0D0")) +
  x_scale + y_scale + coord_cartesian(clip = "off") +
  labs(title = "(a)  What the ranking says",
       subtitle = "Old-value carryover fixed at zero\nin every candidate",
       x = "Share of 400 experiments", y = "Records generated by") +
  theme_figure +
  theme(axis.title.y = element_text(size = 9, colour = grey, margin = margin(r = 6)))

# Panel b: the paired test of first responses separates the two processes.
rejections <- data.frame(process = process_labels, p = rejected)
panel_b <- ggplot(rejections, aes(p, process)) +
  geom_col(aes(x = 1), width = bar_height, fill = paper_colours[["tint"]]) +
  geom_col(width = bar_height, fill = ink) +
  annotate("text", x = rejected[["associability"]] + .025, y = 2,
           label = percent(rejected[["associability"]]), hjust = 0,
           size = text_size, colour = ink) +
  annotate("text", x = .03, y = 1, label = percent(rejected[["value"]]), hjust = 0,
           size = text_size, colour = "white") +
  annotate("text", x = 0, y = 1 - bar_height / 2 - .15,
           label = paste0("where (a) wrongly favors carryover: ", percent(rejected_wrong_wins)),
           hjust = 0, size = text_size, colour = grey) +
  x_scale + y_scale + coord_cartesian(clip = "off") +
  labs(title = "(b)  What the first responses say",
       subtitle = "Paired test rejects equal first-response\nprobabilities for B and D",
       x = "Share of 400 experiments", y = NULL) +
  theme_figure +
  theme(axis.text.y = element_blank())

figure <- panel_a + plot_spacer() + panel_b + plot_layout(widths = c(1, .04, 1))

cat(sprintf("Carryover favored with g_V = 0: carried associability %s, value generalization %s\n",
            percent(share("associability", "carry")), percent(share("value", "carry"))))
cat(sprintf(paste0("First-response test rejects equality: carried associability %s, ",
                   "value generalization %s (%s where carryover wrongly wins)\n"),
            percent(rejected[["associability"]]), percent(rejected[["value"]]),
            percent(rejected_wrong_wins)))
save_figure(figure, "fig11_shared_prediction", 7, 2.6)

# Numbers printed in the text, named by their macros in section5_numbers.tex.
macro_lines <- grep("^\\\\newcommand", readLines("results/section5/section5_numbers.tex"),
                    value = TRUE)
paper <- setNames(sub("^.*\\}\\{(.*)\\}$", "\\1", macro_lines),
                  sub("^\\\\newcommand\\{\\\\([A-Za-z]+)\\}.*$", "\\1", macro_lines))

# Values reported in the paper
stopifnot(
  # Caption: complete records of 160 participants, 400 experiments per process
  restricted$n == 160, restricted$view == "full",
  table(restricted$scenario)[names(process_labels)] == 400,
  # Panel a: no comparison favored an alternative or failed
  !(restricted$decision %in% c("no_carry", "fit_problem")),
  # Section 5.6 and the caption: the percentages drawn, as printed
  sprintf("%.1f", 100 * share("associability", "carry")) == paper[["AssocOmittedCarry"]],
  sprintf("%.1f", 100 * share("value", "carry")) == paper[["ValueOmittedCarry"]],
  sprintf("%.1f", 100 * rejected[["associability"]]) == paper[["AssocInitialRejected"]],
  sprintf("%.1f", 100 * rejected[["value"]]) == paper[["ValueInitialRejected"]],
  sprintf("%.1f", 100 * rejected_wrong_wins) == paper[["ValueWrongFlagged"]]
)
