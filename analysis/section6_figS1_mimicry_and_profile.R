# Supplementary Figure S1 (Section 6.4, Supplement S2.8): (a) how closely each
# alternative, fitted directly to the generating response probabilities,
# imitates them, by the pear trials analyzed; (b) the profile likelihood of the
# carryover of associability g_alpha in the worked example. Reads
# landscape.csv and carryover_profile.csv, which
# analysis/section6_worked_example.R writes. The numbers that the paper prints
# about the figure are checked against the data drawn and against the macros
# in results/section6/section6_numbers.tex.
#   Rscript analysis/section6_figS1_mimicry_and_profile.R

if (!file.exists("R/models.R")) stop("Run this script from the repository root.")
source("R/figure_style.R")
library(patchwork)

# Numbers printed in the text, named by their macros in section6_numbers.tex.
macro_lines <- grep("^\\\\newcommand", readLines("results/section6/section6_numbers.tex"),
                    value = TRUE)
paper <- setNames(sub("^.*\\}\\{(.*)\\}$", "\\1", macro_lines),
                  sub("^\\\\newcommand\\{\\\\([A-Za-z]+)\\}.*$", "\\1", macro_lines))

ink <- paper_colours[["ink"]]
theme_figure <- theme_paper() + theme(axis.title.x = element_text(margin = margin(t = 6)))

# The KL divergence per participant between the probabilities generated by
# carried associability and the best fit of each alternative, for the pear
# trials analyzed (column view: late 8-10, early 1-6, full 1-10).
mimicry <- read.csv("results/section6/landscape.csv")
mimicry <- mimicry[mimicry$scenario == "associability" & mimicry$model != "carry", ]
trial_sets <- c(late = "8–10", early = "1–6", full = "1–10")
mimicry$view_label <- factor(trial_sets[mimicry$view], levels = trial_sets)
mimicry$candidate <- c(fixed = "Fixed-rate", reset = "Reset")[mimicry$model]
fitted_kl <- function(model, view) {
  mimicry$fitted_kl[mimicry$model == model & mimicry$view == view]
}
# Twice the loss in log likelihood relative to the best value of g_alpha.
profile <- read.csv("results/section6/carryover_profile.csv")
profile$loss <- 2 * (profile$nll - min(profile$nll))

panel_mimicry <- ggplot(mimicry, aes(view_label, fitted_kl, group = candidate)) +
  geom_line(aes(linetype = candidate), colour = ink, linewidth = .5) +
  geom_point(aes(shape = candidate), colour = ink, fill = "white", size = 1.8) +
  geom_text(data = subset(mimicry, view == "full"),
            aes(label = candidate), hjust = 0, nudge_x = .12, size = text_size, colour = ink) +
  scale_linetype_manual(values = c("Fixed-rate" = "solid", "Reset" = "22")) +
  scale_shape_manual(values = c("Fixed-rate" = 16, "Reset" = 21)) +
  # KL divergence can exceed 1, so its axis keeps the leading zero.
  scale_y_continuous(limits = c(0, .15), breaks = seq(0, .15, .05),
                     labels = function(x) format(x, trim = TRUE, drop0trailing = TRUE)) +
  scale_x_discrete(expand = expansion(add = c(.4, .9))) +
  labs(x = "Pear trials analyzed for each light", y = "KL divergence per participant",
       title = "(a)  Remaining discrepancy") +
  theme_figure

panel_profile <- ggplot(profile, aes(g_alpha, loss)) +
  geom_line(colour = ink, linewidth = .5) +
  geom_point(colour = ink, size = 1.4) +
  scale_x_continuous(breaks = c(0, .25, .5, .75, 1), labels = c("0", ".25", ".5", ".75", "1")) +
  labs(x = expression("Carryover of associability, " * italic(g)[italic("α")]),
       y = "Twice the loss in log likelihood", title = "(b)  Profile likelihood") +
  theme_figure

cat(sprintf("KL divergence per participant, pear trials 1-10: fixed-rate %.3f, reset %.3f\n",
            fitted_kl("fixed", "full"), fitted_kl("reset", "full")))
cat(sprintf("KL divergence per participant, pear trials 8-10: fixed-rate %.4f, reset %.4f\n",
            fitted_kl("fixed", "late"), fitted_kl("reset", "late")))
cat(sprintf("Profile likelihood of g_alpha: maximum at %s\n",
            format(profile$g_alpha[which.min(profile$nll)])))
save_figure(panel_mimicry | panel_profile, "figS1_mimicry_and_profile", 6.27, 3.2)

# Values reported in the paper
loss_at <- function(g) profile$loss[abs(profile$g_alpha - g) < 1e-9]
eta_at <- function(g) profile$eta[abs(profile$g_alpha - g) < 1e-9]
stopifnot(
  # Supplement S2.8 and Figure S1a: the KL divergences per participant, as
  # printed
  sprintf("%.3f", fitted_kl("fixed", "full")) == paper[["MimicRWAfter"]],
  sprintf("%.3f", fitted_kl("reset", "full")) == paper[["MimicResetFull"]],
  sprintf("%.4f", fitted_kl("fixed", "late")) == paper[["MimicRWLate"]],
  sprintf("%.4f", fitted_kl("reset", "late")) == paper[["MimicResetLate"]],
  # Figure S1 caption: both alternatives come closest on pear trials 8-10
  max(fitted_kl("fixed", "late"), fitted_kl("reset", "late")) <
    min(mimicry$fitted_kl[mimicry$view != "late"]),
  # The drawn values fit inside panel a
  max(mimicry$fitted_kl) < .15,
  # Section 6.4 and Supplement S2.8: g_alpha fixed at 0, .1, ..., 1; the best
  # fit at full carryover; twice the loss stays below 1 down to g_alpha = .5
  # and is .78 there; it exceeds 5 at .4; eta rises from .045 to .082 between
  # g_alpha = 1 and .5 and is at its upper bound of .20 at 0 and .1
  isTRUE(all.equal(profile$g_alpha, seq(0, 1, .1))),
  profile$g_alpha[which.min(profile$nll)] == 1,
  max(profile$loss[profile$g_alpha >= .5]) < 1,
  sprintf("%.2f", loss_at(.5)) == paper[["ProfileHalfLoss"]],
  loss_at(.4) > 5,
  paper_number(eta_at(1), 3) == paper[["ProfileEtaFull"]],
  paper_number(eta_at(.5), 3) == paper[["ProfileEtaHalf"]],
  abs(sapply(c(0, .1), eta_at) - .20) < 1e-8,
  all(profile$converged)
)
